import fs from "fs";
import path from "path";

const csvPath = path.resolve("hc_bits_2026-08-27.csv");
const outPath = path.resolve("packages/backend/convex/headcaseBitsData.ts");

function parseCSV(s) {
  const rows = [];
  let row = [];
  let cell = "";
  let q = false;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (q) {
      if (c === '"') {
        if (s[i + 1] === '"') {
          cell += '"';
          i++;
        } else q = false;
      } else cell += c;
    } else {
      if (c === '"') q = true;
      else if (c === ",") {
        row.push(cell);
        cell = "";
      } else if (c === "\r") continue;
      else if (c === "\n") {
        row.push(cell);
        rows.push(row);
        row = [];
        cell = "";
      } else cell += c;
    }
  }
  if (cell.length || row.length) {
    row.push(cell);
    rows.push(row);
  }
  return rows;
}

const text = fs.readFileSync(csvPath, "utf8");
const rows = parseCSV(text);
const header = rows[0];
const idx = Object.fromEntries(header.map((h, i) => [h, i]));
const data = rows.slice(1).filter((r) => r.some((x) => x && String(x).trim()));

if (data.length !== 855) {
  throw new Error(`Expected 855 data rows, got ${data.length}`);
}

function cell(r, name) {
  return (r[idx[name]] ?? "").trim();
}

const bits = data.map((r, i) => {
  const title = cell(r, "Bit idea");
  const concept = cell(r, "Expanded Concept");
  let resolvedTitle = title;
  if (!resolvedTitle) {
    resolvedTitle = concept
      ? concept.length > 80
        ? `${concept.slice(0, 77)}...`
        : concept
      : `Untitled HeadCase bit ${i + 1}`;
  }
  const politicalRaw = cell(r, "Political").toLowerCase();
  return {
    sourceKey: `hc-csv:${String(i).padStart(3, "0")}`,
    todo: cell(r, "Todo"),
    difficulty: cell(r, "Difficulty"),
    type: cell(r, "Type"),
    category: cell(r, "Category"),
    rating: cell(r, "Rating"),
    political: politicalRaw === "y" || politicalRaw === "yes" || politicalRaw === "true",
    title: resolvedTitle,
    concept,
    techSteps: cell(r, "Programmatic / Tech Steps"),
    notes: cell(r, "Notes / Risks"),
    dialog: r[idx["Outline Dialog/Steps"]] ?? "",
    assets: cell(r, "Assets Needed"),
  };
});

const missingDialog = bits.filter((b) => !b.dialog.trim()).length;
if (missingDialog !== 0) {
  throw new Error(`Expected all dialogs present, ${missingDialog} empty`);
}

const body = `/**
 * HeadCase comedy bits from hc_bits_2026-08-27.csv.
 * Generated by scripts/generate-headcase-bits-data.mjs — do not edit by hand.
 */
export type HeadCaseBit = {
  sourceKey: string;
  todo: string;
  difficulty: string;
  type: string;
  category: string;
  rating: string;
  political: boolean;
  title: string;
  concept: string;
  techSteps: string;
  notes: string;
  dialog: string;
  assets: string;
};

export const HEADCASE_BITS: HeadCaseBit[] = ${JSON.stringify(bits, null, 2)};
`;

fs.writeFileSync(outPath, body);
console.log(`Wrote ${bits.length} bits to ${outPath} (${body.length} bytes)`);
